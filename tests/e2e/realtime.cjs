const fs = require('fs');
const path = require('path');
const OUT = path.join(__dirname, 'output');
fs.mkdirSync(OUT, { recursive: true });
// Real-time checks: touch controls on a phone-sized screen, audio actually playing, render cost.
const { chromium } = require('playwright');
const check = (name, ok, extra = '') => console.log(`${ok ? 'PASS' : 'FAIL'}  ${name}${extra ? '  [' + extra + ']' : ''}`);
(async () => {
  const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
  const ctx = await browser.newContext({ viewport: { width: 844, height: 390 }, hasTouch: true, isMobile: true, deviceScaleFactor: 1 });
  const page = await ctx.newPage();
  const errors = [];
  page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
  page.on('pageerror', (e) => errors.push('PAGEERROR ' + e.message));
  await page.goto(process.env.GAME_URL || 'http://localhost:4173/');
  await page.waitForFunction(() => window.__game && window.__game.frames > 5, null, { timeout: 60000 });
  await page.waitForTimeout(500);
  await page.screenshot({ path: path.join(OUT, 'm_menu.png') });
  const st = () => page.evaluate(() => { const s = window.__game.debugState(); delete s.save; return s; });
  check('mobile: touch controls hidden on the menu', await page.evaluate(() => getComputedStyle(document.getElementById('touch-controls')).display === 'none'));
  await page.tap('#btn-play');
  await page.waitForFunction(() => window.__game.mode === 'play', null, { timeout: 120000 });
  check('mobile: tap on Play starts the game', true);
  check('mobile: touch controls visible in play', await page.evaluate(() => getComputedStyle(document.getElementById('touch-controls')).display === 'block'));
  const sizes = await page.evaluate(() => ['stick', 'btn-jump', 'btn-run', 'btn-pause'].map((id) => { const r = document.getElementById(id).getBoundingClientRect(); return [id, Math.round(r.width), Math.round(r.height), Math.round(r.left), Math.round(r.top)]; }));
  check('mobile: controls are large touch targets (>= 48 px)', sizes.every((s) => s[1] >= 48 && s[2] >= 48), JSON.stringify(sizes));
  const audio = await page.evaluate(() => ({ state: window.__game.audio.ctx && window.__game.audio.ctx.state }));
  check('audio context running after the first tap', audio.state === 'running', audio.state);
  await page.waitForTimeout(4000);
  const a2 = await page.evaluate(() => ({ playing: window.__game.audio.musicPlaying, buffers: [...window.__game.audio.buffers.keys()] }));
  check('music is actually playing (decoded and scheduled)', a2.playing && a2.buffers.includes('music/jungle.mp3'), `buffers=${a2.buffers.length}`);
  check('all 12 effect files + 2 ambience loops decoded', ['step_grass', 'jump', 'land', 'coin', 'star', 'correct', 'wrong', 'splash', 'croc', 'achievement', 'level_complete', 'stone_sink', 'waterfall', 'jungle_amb'].every((n) => a2.buffers.includes(`sfx/${n}.mp3`)), a2.buffers.filter((b) => b.startsWith('sfx')).length + ' sfx');
  check('opening voice line decoded', a2.buffers.includes('voice/intro_jungle.mp3'));
  // Joystick: real (trusted) touch events through the DevTools protocol.
  const client = await ctx.newCDPSession(page);
  const stick = sizes[0];
  const cx = stick[3] + stick[1] / 2, cy = stick[4] + stick[2] / 2;
  const before = await st();
  await client.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: cx, y: cy, id: 1 }] });
  await client.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: cx, y: cy - 60, id: 1 }] });
  await page.waitForTimeout(2500);
  const mid = await st();
  check('joystick pushed up moves Affan forward', mid.z < before.z - 0.8, `z ${before.z.toFixed(2)} -> ${mid.z.toFixed(2)} anim=${mid.animation}`);
  await client.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: cx + 60, y: cy, id: 1 }] });
  await page.waitForTimeout(1800);
  const right = await st();
  check('joystick pushed right moves Affan right', right.x > mid.x + 0.5, `x ${mid.x.toFixed(2)} -> ${right.x.toFixed(2)}`);
  await client.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  await page.waitForTimeout(600);
  const stop = await st(); await page.waitForTimeout(600); const stop2 = await st();
  check('releasing the joystick stops Affan', Math.hypot(stop2.x - stop.x, stop2.z - stop.z) < 0.05);
  const jb = sizes[1];
  await page.evaluate(() => { window.__jumped = false; const g = window.__game; const iv = setInterval(() => { if (!g.body.grounded) { window.__jumped = true; clearInterval(iv); } }, 5); });
  await client.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: jb[3] + jb[1] / 2, y: jb[4] + jb[2] / 2, id: 2 }] });
  await page.waitForTimeout(500);
  await client.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  await page.waitForTimeout(300);
  check('jump button makes Affan jump (and plays the jump sound)', await page.evaluate(() => window.__jumped && window.__game.audio.log.includes('sfx:jump')));
  await page.screenshot({ path: path.join(OUT, 'm_play.png') });
  await page.tap('#btn-pause');
  let s = await st();
  check('pause button pauses the game', s.mode === 'paused' && s.screen === 'pause');
  await page.screenshot({ path: path.join(OUT, 'm_pause.png') });
  const z1 = s.z; await page.waitForTimeout(500);
  await page.tap('#btn-resume');
  s = await st();
  check('resume returns to play', s.mode === 'play');
  // Settings: mute toggles the master gain; slider changes are stored.
  await page.tap('#btn-pause'); await page.tap('#btn-pause-settings');
  await page.tap('#btn-mute');
  const muted = await page.evaluate(() => ({ m: window.__game.audio.settings.muted, saved: JSON.parse(localStorage.getItem('curious-affan-save-v1')).audio.muted }));
  check('sound toggle mutes and is saved', muted.m === true && muted.saved === true);
  await page.tap('#btn-mute');
  await page.evaluate(() => { const el = document.getElementById('vol-music'); el.value = '20'; el.dispatchEvent(new Event('input', { bubbles: true })); });
  check('music volume slider applies', await page.evaluate(() => Math.abs(window.__game.audio.settings.music - 0.2) < 0.001));
  await page.tap('#btn-settings-back'); await page.tap('#btn-resume');
  const info = await page.evaluate(() => { const g = window.__game; g.renderer.info.autoReset = true; g.renderer.render(g.scene, g.camera); return { calls: g.renderer.info.render.calls, tris: g.renderer.info.render.triangles, geos: g.renderer.info.memory.geometries, tex: g.renderer.info.memory.textures }; });
  check('render cost is phone-friendly (draw calls < 250, triangles < 300k)', info.calls < 250 && info.tris < 300000, JSON.stringify(info));
  // Portrait phone layout.
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(800);
  await page.screenshot({ path: path.join(OUT, 'm_portrait.png') });
  check('no console errors on mobile', errors.length === 0, errors.slice(0, 3).join(' ; '));
  await browser.close();
})().catch((e) => { console.error('SCRIPT ERROR', e); process.exit(2); });
